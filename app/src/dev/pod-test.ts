import * as THREE from 'three';
import { SparkRenderer, SplatMesh } from '@sparkjsdev/spark';
const q = new URLSearchParams(location.search);
const id = q.get('id') || 'merch';
const yawDeg = parseFloat(q.get('yaw') || '0');
const meta = await (await fetch('/media/pods/meta.json')).json();
const m = meta[id];
const renderer = new THREE.WebGLRenderer({ antialias: false, preserveDrawingBuffer: true });
renderer.setPixelRatio(1);
renderer.setSize(innerWidth, innerHeight);
document.body.appendChild(renderer.domElement);
const scene = new THREE.Scene();
scene.add(new SparkRenderer({ renderer }));
const f = m.intrinsic[4], H = m.image_size[1];
const fov = (2 * Math.atan(H / 2 / f) * 180) / Math.PI;
const camera = new THREE.PerspectiveCamera(fov, innerWidth / innerHeight, 0.05, 100);
const pod = new SplatMesh({ url: `/media/pods/${id}.spz` });
pod.quaternion.set(1, 0, 0, 0);
scene.add(pod);
await pod.initialized;
const pivot = new THREE.Vector3(0, 0, -m.z_med);
const yaw = (yawDeg * Math.PI) / 180;
camera.position.set(Math.sin(yaw) * m.z_med, 0, -m.z_med + Math.cos(yaw) * m.z_med);
camera.lookAt(pivot);
renderer.setAnimationLoop(() => renderer.render(scene, camera));
setTimeout(() => ((window as any).__ready = true), 500);
