import * as THREE from 'three';
import { loadMeshyRig } from '../guide/meshy';
const q = new URLSearchParams(location.search);
const renderer = new THREE.WebGLRenderer({ antialias: true, preserveDrawingBuffer: true });
renderer.setSize(innerWidth, innerHeight);
renderer.outputColorSpace = THREE.SRGBColorSpace;
document.body.appendChild(renderer.domElement);
const scene = new THREE.Scene();
scene.background = new THREE.Color(0x2a0f3a);
scene.add(new THREE.HemisphereLight(0xffffff, 0x443355, 2.2));
const d = new THREE.DirectionalLight(0xffffff, 1.4); d.position.set(1, 2, 3); scene.add(d);
const cam = new THREE.PerspectiveCamera(30, innerWidth / innerHeight, 0.05, 50);
const { rig, anim } = await loadMeshyRig('/media/guide/hermes-v5.glb');
scene.add(rig.root);
const yaw = parseFloat(q.get('yaw') || '0.3');
cam.position.set(Math.sin(yaw) * 4, 1.0, Math.cos(yaw) * 4);
cam.lookAt(0, 0.85, 0);
const clip = q.get('clip') || 'idle';
for (const a of (anim as any).actions.values()) a.setEffectiveWeight(0);
const act = (anim as any).actions.get(clip);
act.reset().setEffectiveWeight(1).play();
anim.mixer.update(parseFloat(q.get('t') || '1'));
renderer.render(scene, cam);
(window as any).__ready = true;
